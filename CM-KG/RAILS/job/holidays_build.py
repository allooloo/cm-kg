r"""holidays_build.py — CHAIN-CLOSE B3 (CEO order 2026-10-29): writes holidays.py, the one table of exchange closures the market-date rule reads, from the
dated source reads in holidays-src\*.json (one row per node market: its primary exchange, the exchange's own page, the read date, full-day closures on weekdays).
Sourced or blank: a market whose calendar was not read carries no dates and its rule stays weekends only. Rebuild when a calendar is re-read:
    python -I -X utf8 holidays_build.py      → holidays.py (generated; never edited by hand)"""
import json, glob, os, datetime, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE); import roster
src = {}
for f in sorted(glob.glob(os.path.join(HERE, 'holidays-src', '*.json'))): src.update(json.load(open(f, encoding='utf-8')))
codes = roster.codes(); missing = [c for c in codes if c not in src]
rows = {}
for cc in codes:
    s = src.get(cc) or {}
    dates = sorted({d for y in ('2026', '2027') for d in (s.get(y) or [])})
    for d in dates: assert datetime.date.fromisoformat(d).weekday() < 5, (cc, d)   # weekdays only
    rows[cc] = {'exchange': s.get('exchange'), 'source_url': s.get('source_url'), 'read': s.get('read'), 'through': max((y for y in ('2026', '2027') if s.get(y)), default=None), 'dates': dates}
out = ['# holidays.py — GENERATED by holidays_build.py from holidays-src\\*.json (CHAIN-CLOSE, CEO order 2026-10-29). Do not edit by hand.',
       '# One table: for each node market, the full-day closures of its primary exchange on weekdays, read from the exchange\'s own page (source_url, read date).',
       '# The node market-date rule (job_node.py last_trading) rolls a closure back like a weekend. A market with no dates (no calendar read) rolls weekends only.',
       '# "through" = the last calendar year the exchange has published; after it the rule is weekends only again until the table is rebuilt.',
       'HOLIDAYS = {']
for cc, r in rows.items():
    out.append(f"    {cc!r}: {{'exchange': {r['exchange']!r}, 'source_url': {r['source_url']!r}, 'read': {r['read']!r}, 'through': {r['through']!r},")
    out.append(f"           'dates': {r['dates']!r}}},")
out += ['}', 'CLOSED = {cc: frozenset(r["dates"]) for cc, r in HOLIDAYS.items()}', '',
        'def closed(cc, d):', '    """True when the market of node cc is shut all day on date d (a weekday closure on its exchange\'s published calendar)."""',
        '    return d.isoformat() in CLOSED.get(cc, ())', '']
open(os.path.join(HERE, 'holidays.py'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
blank = [c for c, r in rows.items() if not r['dates']]
print('holidays.py written ·', len(rows), 'markets ·', sum(len(r['dates']) for r in rows.values()), 'closure dates · blank (weekends only):', blank, '· not on any source read:', missing)
